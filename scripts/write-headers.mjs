// Writes dist/_headers after the build: a year of immutable caching for each
// content-hashed file Astro emitted under /_astro/, listed by exact path.
//
// Not a /_astro/* wildcard: that would also mark the 404 for a missing file
// immutable. While a deploy rolls out, a page from the new version can ask a
// location still on the old one for an asset it doesn't have yet, and that
// 404 would then stick in the visitor's browser for a year.
// Everything else keeps Cloudflare's default: revalidate on every request.
//
// usage: node scripts/write-headers.mjs (run by `pnpm build`)
import { readdirSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const dist = 'dist'
// Cloudflare reads at most this many rules from _headers.
const limit = 100

const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)],
  )

const paths = walk(join(dist, '_astro'))
  .map((file) => '/' + relative(dist, file).split(sep).join('/'))
  .sort()

if (paths.length > limit) {
  console.error(`_headers: ${paths.length} hashed files, more than Cloudflare's ${limit}-rule limit. Narrow the rules in scripts/write-headers.mjs.`)
  process.exit(1)
}

const rules = paths.map((path) => `${path}\n  Cache-Control: public, max-age=31536000, immutable\n`)
writeFileSync(join(dist, '_headers'), `# Generated by scripts/write-headers.mjs.\n${rules.join('')}`)
console.log(`_headers: immutable caching for ${paths.length} hashed files`)
